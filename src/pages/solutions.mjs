function compare(rows) {
  return `<table class="compare"><thead><tr><th scope="col">업무</th><th scope="col">지금</th><th scope="col" class="us">에셋온에서는</th></tr></thead><tbody>${rows.map(([a, b, c]) => `<tr><td>${a}</td><td class="now">${b}</td><td class="us">${c}</td></tr>`).join('')}</tbody></table>`;
}
const steps = (items) => `<ol class="steps-list">${items.map(([b, s]) => `<li><div><b>${b}</b><span>${s}</span></div></li>`).join('')}</ol>`;
const links = (items) => `<div class="demo-rows">${items.map(([ic, t, d, h]) => `<a class="demo-row" href="${h}"><span class="ico">${icon(ic)}</span><span><b>${t}</b><span>${d}</span></span></a>`).join('')}</div>`;

function build({ path, crumb, title, lede, art, compareHead, rows, startHead, startLede, start, plan, featLinks, metaTitle, metaDesc, cta }) {
  const body = `
${pageHero({ crumb: [['누가 쓰나요'], [crumb]], title, lede, actions: '<a class="btn btn-primary" href="/signup">사전 신청하기</a><a class="btn btn-line" href="/signup?type=demo">데모 신청</a>', art: art + exampleNote() })}
${sec(`${head(compareHead)}${compare(rows)}`)}
${sec(`<div class="split-5-7"><div>${head(startHead, startLede)}<div class="callout mt-3"><b>맞는 플랜</b> — ${plan} <a class="text-link" href="/pricing">요금 보기</a></div></div>${steps(start)}</div>`, 'mist')}
${sec(`${head('먼저 쓰게 될 기능')}${links(featLinks)}`)}
${ctaBand(...(cta || []))}`;
  return page({ path, title: metaTitle, description: metaDesc, active: 'solutions', body, jsonld: [breadcrumbLd([[crumb, path]])] });
}

